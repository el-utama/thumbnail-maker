/* Thumbnail Lab — canvas renderer.
   Layer order: photo → grade → vignette → scrim → meta chips → title → grain.
   Typography is drawn by code, never generated by the image model. */

const Renderer = (() => {
  const analysisCache = new WeakMap();
  const grainCache = new Map();

  const clamp = (v, a, b) => Math.min(b, Math.max(a, v));

  function fontString(key, size) {
    const f = FONTS[key] || FONTS.anton;
    const style = f.style ? `${f.style} ` : '';
    const weight = f.weight ? `${f.weight} ` : '400 ';
    return `${style}${weight}${Math.round(size)}px "${f.family}"`;
  }

  function fontFor(template, word) {
    return word.accent && template.accentFont ? template.accentFont : template.font;
  }

  function prepare(ctx, template, size) {
    ctx.textBaseline = 'alphabetic';
    ctx.textAlign = 'left';
    ctx.shadowColor = 'rgba(0,0,0,0.55)';
    ctx.shadowBlur = size * 0.22;
    ctx.shadowOffsetY = size * 0.05;
    ctx.letterSpacing = `${size * (template.letterSpacing || 0)}px`;
  }

  function applyTransform(text, template) {
    return template.transform === 'upper' ? text.toUpperCase() : text;
  }

  function accentSet(accent) {
    return new Set(
      String(accent || '')
        .toLowerCase()
        .split(/[^a-z0-9']+/)
        .filter(Boolean)
    );
  }

  function markWords(line, accentWords) {
    return line.split(/\s+/).filter(Boolean).map((raw) => {
      const core = raw.toLowerCase().replace(/[^a-z0-9']/g, '');
      return { raw, accent: accentWords.has(core) };
    });
  }

  function wrapText(ctx, text, maxWidth, template, accentWords, size) {
    const paragraphs = String(text || '').split(/\n|\|/);
    const lines = [];
    for (const paragraph of paragraphs) {
      const words = markWords(applyTransform(paragraph, template), accentWords);
      if (!words.length) continue;
      let line = [];
      let width = 0;
      const space = size * 0.28;
      for (const word of words) {
        const font = fontFor(template, word);
        const s = word.accent && template.accentScale ? size * template.accentScale : size;
        ctx.font = fontString(font, s);
        const w = ctx.measureText(word.raw).width;
        const add = line.length ? space : 0;
        if (line.length && width + add + w > maxWidth) {
          lines.push({ words: line, width });
          line = [word];
          width = w;
        } else {
          line.push(word);
          width += add + w;
        }
      }
      if (line.length) lines.push({ words: line, width });
    }
    return lines;
  }

  function measureLine(ctx, line, template, size) {
    const space = size * 0.28;
    let width = 0;
    line.words.forEach((word, i) => {
      const font = fontFor(template, word);
      const s = word.accent && template.accentScale ? size * template.accentScale : size;
      ctx.font = fontString(font, s);
      width += ctx.measureText(word.raw).width + (i ? space : 0);
    });
    return width;
  }

  function drawWords(ctx, line, x, baseline, template, size, theme, gradient) {
    const space = size * 0.28;
    let cursor = x;
    for (const word of line.words) {
      const isAccent = word.accent;
      const font = fontFor(template, word);
      const s = isAccent && template.accentScale ? size * template.accentScale : size;
      ctx.font = fontString(font, s);
      const w = ctx.measureText(word.raw).width;
      const drawY = baseline - (isAccent && template.accentScale ? (s - size) * 0.72 : 0);

      if (isAccent && template.accentMode === 'block') {
        const px = s * 0.1;
        const py = s * 0.14;
        ctx.save();
        ctx.shadowColor = 'transparent';
        ctx.fillStyle = theme.accent;
        roundRect(ctx, cursor - px, drawY - s * 0.74 - py * 0.2, w + px * 2, s * 0.86 + py, s * 0.03);
        ctx.fill();
        ctx.restore();
        ctx.fillStyle = theme.blockText || '#0a0a0a';
      } else if (isAccent && template.accentMode === 'gradient') {
        ctx.fillStyle = gradient || theme.accent;
      } else if (isAccent) {
        ctx.fillStyle = template.accentOverride || theme.accent;
      } else {
        ctx.fillStyle = template.bodyGrad && gradient ? gradient : theme.text;
      }

      if (template.stroke) {
        ctx.save();
        ctx.shadowColor = 'transparent';
        ctx.strokeStyle = 'rgba(0,0,0,0.82)';
        ctx.lineWidth = s * 0.085;
        ctx.lineJoin = 'round';
        ctx.strokeText(word.raw, cursor, drawY);
        ctx.restore();
      }
      ctx.fillText(word.raw, cursor, drawY);
      cursor += w + space;
    }
  }

  function roundRect(ctx, x, y, w, h, r) {
    const radius = Math.min(r, w / 2, h / 2);
    ctx.beginPath();
    ctx.moveTo(x + radius, y);
    ctx.arcTo(x + w, y, x + w, y + h, radius);
    ctx.arcTo(x + w, y + h, x, y + h, radius);
    ctx.arcTo(x, y + h, x, y, radius);
    ctx.arcTo(x, y, x + w, y, radius);
    ctx.closePath();
  }

  function drawCover(ctx, img, W, H) {
    const iw = img.naturalWidth || img.width;
    const ih = img.naturalHeight || img.height;
    const scale = Math.max(W / iw, H / ih);
    const dw = iw * scale;
    const dh = ih * scale;
    ctx.drawImage(img, (W - dw) / 2, (H - dh) / 2, dw, dh);
  }

  function drawPlaceholder(ctx, W, H, theme) {
    const g = ctx.createLinearGradient(0, 0, W * 0.4, H);
    g.addColorStop(0, theme.tintTop);
    g.addColorStop(1, theme.tintBottom);
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, W, H);

    const glowA = ctx.createRadialGradient(W * 0.78, H * 0.22, 0, W * 0.78, H * 0.22, W * 0.55);
    glowA.addColorStop(0, hexA(theme.accent, 0.35));
    glowA.addColorStop(1, 'rgba(0,0,0,0)');
    ctx.fillStyle = glowA;
    ctx.fillRect(0, 0, W, H);

    const glowB = ctx.createRadialGradient(W * 0.2, H * 0.85, 0, W * 0.2, H * 0.85, W * 0.5);
    glowB.addColorStop(0, hexA(theme.tintTop, 0.55));
    glowB.addColorStop(1, 'rgba(0,0,0,0)');
    ctx.fillStyle = glowB;
    ctx.fillRect(0, 0, W, H);
  }

  function hexA(hex, a) {
    const h = hex.replace('#', '');
    const n = parseInt(h.length === 3 ? h.split('').map((c) => c + c).join('') : h, 16);
    return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`;
  }

  function applyGrade(ctx, W, H, theme, state) {
    const strength = theme.tintStrength * (0.55 + state.scrim * 0.45);
    ctx.save();
    ctx.globalCompositeOperation = 'soft-light';
    const g = ctx.createLinearGradient(0, 0, W * 0.22, H);
    g.addColorStop(0, theme.tintTop);
    g.addColorStop(1, theme.tintBottom);
    ctx.globalAlpha = strength;
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, W, H);
    ctx.restore();

    ctx.save();
    ctx.globalCompositeOperation = 'multiply';
    ctx.globalAlpha = 0.22;
    ctx.fillStyle = theme.tintBottom;
    ctx.fillRect(0, 0, W, H);
    ctx.restore();

    const leak = ctx.createRadialGradient(W * 0.9, H * 0.05, 0, W * 0.9, H * 0.05, W * 0.5);
    leak.addColorStop(0, hexA(theme.accent, 0.16));
    leak.addColorStop(1, 'rgba(0,0,0,0)');
    ctx.save();
    ctx.globalCompositeOperation = 'screen';
    ctx.fillStyle = leak;
    ctx.fillRect(0, 0, W, H);
    ctx.restore();

    const v = ctx.createRadialGradient(W / 2, H * 0.48, H * 0.25, W / 2, H * 0.5, W * 0.72);
    v.addColorStop(0, 'rgba(0,0,0,0)');
    v.addColorStop(1, 'rgba(0,0,0,0.58)');
    ctx.fillStyle = v;
    ctx.fillRect(0, 0, W, H);
  }

  function imageEnergy(img) {
    if (!img) return null;
    if (analysisCache.has(img)) return analysisCache.get(img);
    // Low edge energy + low luminance = a calm place to set type.
    // (Keeping this cheap: 64×36 sample, computed once per image.)
    const c = document.createElement('canvas');
    c.width = 64;
    c.height = 36;
    const cx = c.getContext('2d', { willReadFrequently: true });
    cx.drawImage(img, 0, 0, 64, 36);
    const data = cx.getImageData(0, 0, 64, 36).data;

    const region = (x0, x1, y0, y1) => {
      let energy = 0;
      let lum = 0;
      let count = 0;
      for (let y = y0; y < y1; y++) {
        for (let x = x0; x < x1; x++) {
          const i = (y * 64 + x) * 4;
          const l = (0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2]) / 255;
          lum += l;
          const j = (y * 64 + Math.min(63, x + 1)) * 4;
          const l2 = (0.2126 * data[j] + 0.7152 * data[j + 1] + 0.0722 * data[j + 2]) / 255;
          energy += Math.abs(l - l2);
          count++;
        }
      }
      return { energy: energy / count, lum: lum / count };
    };

    const result = {
      left: region(4, 24, 22, 34),
      right: region(40, 60, 22, 34),
      top: region(0, 64, 0, 10),
    };
    analysisCache.set(img, result);
    return result;
  }

  function scrimLayer(ctx, W, H, box, template, theme, state) {
    const power = (template.scrimPower || 1) * state.scrim;
    if (power <= 0.02) return;
    const [r, g, b] = theme.scrim;
    const solid = (a) => `rgba(${r},${g},${b},${a})`;

    ctx.save();
    const side = template.scrim;
    if (side === 'left' || side === 'bottom-left') {
      const l = ctx.createLinearGradient(0, 0, W * 0.72, 0);
      l.addColorStop(0, solid(0.86 * power));
      l.addColorStop(0.55, solid(0.38 * power));
      l.addColorStop(1, solid(0));
      ctx.fillStyle = l;
      ctx.fillRect(0, 0, W, H);
    }
    if (side === 'right' || side === 'bottom-right') {
      const rgt = ctx.createLinearGradient(W, 0, W * 0.35, 0);
      rgt.addColorStop(0, solid(0.82 * power));
      rgt.addColorStop(0.6, solid(0.3 * power));
      rgt.addColorStop(1, solid(0));
      ctx.fillStyle = rgt;
      ctx.fillRect(0, 0, W, H);
    }
    if (side === 'bottom' || side === 'bottom-left' || side === 'bottom-right' || side === 'subtle') {
      const start = side === 'subtle' ? 0.42 : 0.3;
      const btm = ctx.createLinearGradient(0, H * start, 0, H);
      btm.addColorStop(0, solid(0));
      btm.addColorStop(0.55, solid(0.62 * power));
      btm.addColorStop(1, solid(0.92 * power));
      ctx.fillStyle = btm;
      ctx.fillRect(0, 0, W, H);
    }
    if (side === 'center') {
      const c = ctx.createRadialGradient(box.cx, box.cy, 0, box.cx, box.cy, Math.max(box.w, W * 0.42) * 0.9);
      c.addColorStop(0, solid(0.78 * power));
      c.addColorStop(0.7, solid(0.35 * power));
      c.addColorStop(1, solid(0));
      ctx.fillStyle = c;
      ctx.fillRect(0, 0, W, H);
    }
    ctx.restore();
  }

  function sampleBox(ctx, W, H, box) {
    const x = clamp(Math.round(box.x), 0, W - 1);
    const y = clamp(Math.round(box.y), 0, H - 1);
    const w = clamp(Math.round(box.w), 1, W - x);
    const h = clamp(Math.round(box.h), 1, H - y);
    let data;
    try {
      data = ctx.getImageData(x, y, w, h).data;
    } catch (e) {
      return { lum: 0.5, min: 0.3, max: 0.7 };
    }
    let sum = 0;
    let min = 1;
    let max = 0;
    let count = 0;
    const step = Math.max(1, Math.floor(data.length / 4 / 900)) * 4;
    for (let i = 0; i < data.length; i += step) {
      const l = (0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2]) / 255;
      sum += l;
      min = Math.min(min, l);
      max = Math.max(max, l);
      count++;
    }
    return { lum: sum / count, min, max };
  }

  function relativeLum(r, g, b) {
    const f = (c) => {
      const s = c / 255;
      return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
    };
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
  }

  function parseColor(c) {
    if (c.startsWith('#')) {
      const h = c.slice(1);
      const n = parseInt(h.length === 3 ? h.split('').map((x) => x + x).join('') : h, 16);
      return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
    }
    const m = c.match(/rgba?\(([^)]+)\)/);
    if (m) return m[1].split(',').slice(0, 3).map((v) => parseFloat(v));
    return [255, 255, 255];
  }

  function contrastRatio(a, b) {
    const la = relativeLum(...a);
    const lb = relativeLum(...b);
    return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
  }

  function grain(ctx, W, H, amount) {
    if (amount <= 0.01) return;
    const key = `${W}x${H}`;
    let canvas = grainCache.get(key);
    if (!canvas) {
      canvas = document.createElement('canvas');
      canvas.width = W;
      canvas.height = H;
      const gx = canvas.getContext('2d');
      const img = gx.createImageData(W, H);
      for (let i = 0; i < img.data.length; i += 4) {
        const v = 100 + Math.random() * 90;
        img.data[i] = v;
        img.data[i + 1] = v;
        img.data[i + 2] = v;
        img.data[i + 3] = 255;
      }
      gx.putImageData(img, 0, 0);
      grainCache.set(key, canvas);
    }
    ctx.save();
    ctx.globalCompositeOperation = 'overlay';
    ctx.globalAlpha = amount * 0.1;
    ctx.drawImage(canvas, 0, 0);
    ctx.restore();
  }

  function pill(ctx, text, x, y, size, bg, fg, alignRight) {
    ctx.save();
    ctx.shadowColor = 'transparent';
    ctx.font = fontString('grotesk', size);
    ctx.letterSpacing = `${size * 0.12}px`;
    const w = ctx.measureText(text).width + size * 1.1;
    const h = size * 1.9;
    const px = alignRight ? x - w : x;
    ctx.fillStyle = bg;
    roundRect(ctx, px, y, w, h, h / 2);
    ctx.fill();
    ctx.fillStyle = fg;
    ctx.textBaseline = 'middle';
    ctx.fillText(text, px + size * 0.55, y + h / 2 + size * 0.03);
    ctx.restore();
    return { x: px, y, w, h };
  }

  function render(ctx, W, H, state, img) {
    const theme = THEMES.find((t) => t.id === state.theme) || THEMES[0];
    const template = TEMPLATES.find((t) => t.id === state.template) || TEMPLATES[0];
    const pad = W * 0.055;

    ctx.clearRect(0, 0, W, H);
    if (img) drawCover(ctx, img, W, H);
    else drawPlaceholder(ctx, W, H, theme);
    applyGrade(ctx, W, H, theme, state);

    const small = H < 220;

    // Auto side: keep type on the calmer, darker half of the lower band.
    // Only override the designed side when the gain is clear, so layouts stay intentional.
    let align = template.align;
    let anchorX = template.anchorX;
    let mirror = false;
    const energy = imageEnergy(img);
    if (state.autoPlace && template.align !== 'center' && energy) {
      const score = (r) => r.energy + r.lum * 0.55;
      const leftScore = score(energy.left);
      const rightScore = score(energy.right);
      const keepLeft = template.align === 'left';
      if (keepLeft && rightScore < leftScore * 0.72) {
        align = 'right';
        anchorX = 1 - template.anchorX;
        mirror = true;
      } else if (!keepLeft && leftScore < rightScore * 0.72) {
        align = 'left';
        anchorX = 1 - template.anchorX;
        mirror = true;
      }
    }

    const accentWords = accentSet(state.accent);
    const maxWidth = W * template.maxWidth;
    let size = H * template.size * state.scale;
    const lineHeight = template.lineHeight;

    let lines = [];
    for (let guard = 0; guard < 40; guard++) {
      lines = wrapText(ctx, state.title, maxWidth, template, accentWords, size);
      const widest = Math.max(...lines.map((l) => measureLine(ctx, l, template, size)), 0);
      const blockH = lines.length * size * lineHeight;
      if (widest <= maxWidth && blockH <= H * template.maxHeight) break;
      size *= 0.955;
    }
    lines = wrapText(ctx, state.title, maxWidth, template, accentWords, size);

    const gapSub = size * 0.45;
    const subBase = Math.max(13, H * 0.0225);
    const blockH = lines.length * size * lineHeight;
    const sub = !small && state.subtitle ? applyTransform(state.subtitle, { transform: 'upper' }) : '';
    let subSize = subBase;
    if (sub) {
      ctx.font = fontString('grotesk', subSize);
      ctx.letterSpacing = `${subSize * 0.14}px`;
      const natural = ctx.measureText(sub).width;
      const capW = W * Math.min(0.74, template.maxWidth + 0.06);
      if (natural > capW) subSize = subBase * (capW / natural);
    }
    ctx.font = fontString('grotesk', subSize);
    ctx.letterSpacing = `${subSize * 0.14}px`;
    const subW = sub ? Math.min(ctx.measureText(sub).width, W * 0.74) : 0;

    let top;
    if (template.anchor === 'middle') {
      const total = blockH + (sub ? gapSub + subSize : 0);
      top = H * template.anchorY - total / 2 + H * state.offsetY;
    } else {
      const total = blockH + (sub && template.subPos === 'above' ? gapSub + subSize : sub ? gapSub + subSize : 0);
      top = H * template.anchorY - total + H * state.offsetY;
    }
    const blockLeft = align === 'left' ? W * anchorX + W * state.offsetX
      : align === 'right' ? W * anchorX - maxWidth + W * state.offsetX
        : W * anchorX - maxWidth / 2 + W * state.offsetX;

    const widest = Math.max(...lines.map((l) => measureLine(ctx, l, template, size)), 1);
    const box = {
      x: align === 'left' ? blockLeft : align === 'right' ? blockLeft + (maxWidth - widest) : blockLeft + (maxWidth - widest) / 2,
      y: top,
      w: widest,
      h: blockH + (sub ? gapSub + subSize : 0),
    };

    // YouTube stamps the duration in the bottom-right corner. Lift the type
    // out of that corner instead of letting the overlay eat the hook.
    const safeW = W * 0.24;
    const safeH = H * 0.16;
    const safeZone = { x: W - safeW, y: H - safeH, w: safeW, h: safeH };
    if (!small && box.x + box.w > safeZone.x && box.y + box.h > safeZone.y) {
      const shift = box.y + box.h - safeZone.y + size * 0.2;
      top -= shift;
      box.y -= shift;
      if (top < H * 0.06) {
        const back = H * 0.06 - top;
        top += back;
        box.y += back;
      }
    }
    box.cx = box.x + box.w / 2;
    box.cy = box.y + box.h / 2;

    const resolvedScrim = template.scrim === 'bottom-left' && align === 'right' ? 'bottom-right'
      : template.scrim === 'left' && align === 'right' ? 'right'
        : template.scrim === 'bottom-right' && align === 'left' ? 'bottom-left'
          : template.scrim;
    scrimLayer(ctx, W, H, box, { ...template, align, scrim: resolvedScrim }, theme, state);

    // Contrast is measured on the actual pixels behind the type, after scrim.
    const bg = sampleBox(ctx, W, H, box);
    const textRgb = parseColor(theme.text);
    const ratio = contrastRatio(textRgb, [bg.lum * 255, bg.lum * 255, bg.lum * 255]);

    // Meta row: channel + genre chip (top-left), badge (top-right).
    const meta = {};
    const metaSize = Math.max(13, H * 0.019);
    if (!small && (state.genre || state.channel)) {
      const label = state.genre ? state.genre.toUpperCase() : '';
      let cursor = pad;
      if (label) {
        const chip = pill(ctx, label, cursor, pad, metaSize, theme.chipBg, theme.chipText, false);
        meta.chip = chip;
        cursor = chip.x + chip.w + metaSize * 0.8;
      }
      if (state.channel) {
        ctx.save();
        ctx.shadowColor = 'transparent';
        ctx.font = fontString('grotesk', metaSize);
        ctx.letterSpacing = `${metaSize * 0.14}px`;
        ctx.fillStyle = theme.sub;
        ctx.textBaseline = 'middle';
        ctx.fillText(state.channel.toUpperCase(), cursor, pad + metaSize * 0.98);
        ctx.restore();
      }
    }
    if (!small && state.badge) {
      meta.badge = pill(ctx, state.badge.toUpperCase(), W - pad, pad, metaSize, theme.badgeBg, theme.badgeText, true);
    }

    // Title block.
    ctx.save();
    prepare(ctx, template, size);
    const gradient = ctx.createLinearGradient(0, top, 0, top + blockH);
    if (theme.goldGrad) {
      gradient.addColorStop(0, theme.goldGrad[0]);
      gradient.addColorStop(0.55, theme.goldGrad[1]);
      gradient.addColorStop(1, theme.goldGrad[2]);
    } else {
      gradient.addColorStop(0, theme.text);
      gradient.addColorStop(1, theme.text);
    }

    if (template.ornament) {
      ctx.save();
      ctx.shadowColor = 'transparent';
      ctx.strokeStyle = hexA(theme.accent, 0.85);
      ctx.lineWidth = Math.max(1.5, size * 0.02);
      const lw = Math.min(widest * 0.9, W * 0.5);
      ctx.beginPath();
      ctx.moveTo(W * 0.5 - lw / 2, top - size * 0.55);
      ctx.lineTo(W * 0.5 + lw / 2, top - size * 0.55);
      ctx.moveTo(W * 0.5 - lw / 2, top + blockH + size * 0.4);
      ctx.lineTo(W * 0.5 + lw / 2, top + blockH + size * 0.4);
      ctx.stroke();
      ctx.restore();
    }

    lines.forEach((line, i) => {
      const lineW = measureLine(ctx, line, template, size);
      const x = align === 'left' ? box.x : align === 'right' ? box.x + box.w - lineW : box.x + (box.w - lineW) / 2;
      const baseline = top + size * lineHeight * i + size * 0.78;
      prepare(ctx, template, size);
      drawWords(ctx, line, x, baseline, template, size, theme, gradient);
    });

    let subY = null;
    if (sub) {
      const sy = template.subPos === 'above' ? top - gapSub : top + blockH + gapSub;
      ctx.save();
      prepare(ctx, { ...template, letterSpacing: 0.14 }, subSize);
      ctx.font = fontString('grotesk', subSize);
      ctx.shadowColor = 'rgba(0,0,0,0.45)';
      ctx.shadowBlur = subSize * 0.5;
      ctx.fillStyle = theme.sub;
      ctx.textBaseline = 'alphabetic';
      let sx = box.x;
      if (align === 'right') sx = box.x + box.w - subW;
      if (align === 'center') sx = box.x + (box.w - subW) / 2;
      ctx.fillText(sub, sx, sy + subSize * 0.8);
      ctx.restore();
      subY = sy;
    }
    ctx.restore();

    if (template.rule && state.title) {
      ctx.save();
      ctx.shadowColor = 'transparent';
      ctx.strokeStyle = theme.accent;
      ctx.lineWidth = Math.max(2, H * 0.003);
      ctx.beginPath();
      ctx.moveTo(box.x, top - size * 0.75);
      ctx.lineTo(box.x + Math.min(size * 1.6, widest), top - size * 0.75);
      ctx.stroke();
      ctx.restore();
    }

    grain(ctx, W, H, state.grain);

    const words = String(state.title || '').trim().split(/\s+/).filter(Boolean).length;
    const intersects = (b) => b && !(b.x + b.w < safeZone.x || b.x > safeZone.x + safeZone.w || b.y + b.h < safeZone.y || b.y > safeZone.y + safeZone.h);
    const capPx = size * 0.72 * (120 / W);

    return {
      themeId: theme.id,
      templateId: template.id,
      fontPx: size,
      lines: lines.length,
      words,
      titleBox: box,
      subY,
      meta,
      safeZone,
      safeZoneClear: !intersects(box) && !intersects(meta.badge),
      coverage: (box.w * box.h) / (W * H),
      contrast: ratio,
      backgroundLum: bg.lum,
      capPx,
      align,
      mirrored: mirror,
    };
  }

  return { render, fontString, parseColor, contrastRatio, hexA, roundRect };
})();
